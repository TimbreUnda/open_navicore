#!/usr/bin/env python3
"""Generate prototype-free ARM trampolines for every PAS application slot.

The source manifest is the checked, binary-derived PAS proxy inventory.  This
generator deliberately consumes only interface identity and slot number: no C
prototype is invented for an unrecovered method.
"""

from __future__ import annotations

import argparse
import csv
import pathlib


def load(path: pathlib.Path) -> list[dict[str, str]]:
    rows = [r for r in csv.DictReader(path.open(newline="", encoding="utf-8"))
            if r["slot_kind"] == "pure_virtual_application"]
    keys = [(r["adapter"], int(r["slot"])) for r in rows]
    if len(rows) != 199 or len(set(keys)) != len(rows):
        raise SystemExit(f"expected 199 unique application slots, got {len(rows)}")
    if len({r["interface"] for r in rows}) != 25:
        raise SystemExit("expected 25 callback interfaces")
    return rows


def symbol(index: int, row: dict[str, str]) -> str:
    adapter = "root" if row["adapter"] == "root" else f"a{int(row['adapter'])}"
    return f"mock_raw_cb_{index:03d}_{adapter}_s{int(row['slot'])}"


def emit_asm(rows: list[dict[str, str]]) -> str:
    out = [
        "/* Generated by tools/generators/generate_raw_callback_trampolines.py. */",
        ".syntax unified", ".arm", ".text", ".align 2", "",
    ]
    for index, row in enumerate(rows):
        sym = symbol(index, row)
        out += [
            f".global {sym}", f".hidden {sym}", f".type {sym}, %function",
            f"{sym}:",
            "    stmdb sp!, {r12, lr}",
            f"    ldr r12, ={index}",
            "    b mock_raw_callback_enter",
            f".size {sym}, .-{sym}", "",
        ]
    return "\n".join(out)


def emit_table(rows: list[dict[str, str]]) -> str:
    interface_ids = {name: index for index, name in enumerate(dict.fromkeys(
        row["interface"] for row in rows))}
    out = [
        "/* Generated by tools/generators/generate_raw_callback_trampolines.py. */",
        '#include "mock_raw_callback_capture_internal.h"', "",
        "#include <stddef.h>", "",
        "#ifdef MOCK_RAW_CALLBACK_HOST_TEST",
        "#define MOCK_RAW_TRAMPOLINE(name) NULL",
        "#else",
    ]
    for index, row in enumerate(rows):
        out.append(f"extern void {symbol(index, row)}(void);")
    out += ["#define MOCK_RAW_TRAMPOLINE(name) name", "#endif", "",
            "const MockRawCallbackSlot mock_raw_callback_slots[] = {"]
    for index, row in enumerate(rows):
        adapter = "MOCK_RAW_CALLBACK_ROOT" if row["adapter"] == "root" else f"{int(row['adapter'])}u"
        iface = row["interface"].replace('"', '\\"')
        out.append(f'    {{{adapter}, {int(row["slot"])}u, {interface_ids[row["interface"]]}u, "{iface}", MOCK_RAW_TRAMPOLINE({symbol(index, row)})}},')
    out += [
        "};",
        "const uint32_t mock_raw_callback_slot_count =",
        "    (uint32_t)(sizeof(mock_raw_callback_slots) / sizeof(mock_raw_callback_slots[0]));",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("manifest", type=pathlib.Path)
    ap.add_argument("assembly", type=pathlib.Path)
    ap.add_argument("table", type=pathlib.Path)
    ns = ap.parse_args()
    rows = load(ns.manifest)
    ns.assembly.write_text(emit_asm(rows), encoding="utf-8")
    ns.table.write_text(emit_table(rows), encoding="utf-8")
    print(f"generated {len(rows)} raw callback trampolines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
