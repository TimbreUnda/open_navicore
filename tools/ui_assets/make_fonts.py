#!/usr/bin/env python3
"""Generates the LVGL navigation fonts from the design's Montserrat.

The design (Uconnect Media - Navigation) uses Montserrat at a few sizes and
weights, with Cyrillic street names. LVGL's built-in Montserrat has one
weight and no Cyrillic, so static instances are cut from the variable
Montserrat (OFL, fonts/) and converted with lv_font_conv:

  python3 tools/ui_assets/make_fonts.py /path/to/lv_font_conv.js

Needs fontTools + brotli and node. Output: backends/osmand/ui/assets/.
Each font falls back to the built-in Montserrat of the nearest size so
LV_SYMBOL_* glyphs keep working.
"""
import os
import re
import subprocess
import sys
import tempfile

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FONTS = os.path.join(ROOT, 'tools', 'ui_assets', 'fonts')
OUT = os.path.join(ROOT, 'backends', 'osmand', 'ui', 'assets')

# (size px, CSS weight) pairs used by the design.
STYLES = [(14, 400), (14, 600), (14, 700), (14, 800),
          (20, 400), (20, 600), (20, 700),
          (24, 700), (24, 800),
          (28, 700), (28, 800)]
LATIN = '0x20-0x7E,0xA0-0xFF,0x2013-0x2014,0x2018-0x201E,0x2022,0x2026,0x2039-0x203A,0x20AC'
CYRILLIC = '0x400-0x45F,0x490-0x491,0x2116'
# Built-in fallbacks enabled in lv_conf.h.
BUILTIN = {14: 14, 20: 20, 24: 24, 28: 28}


def instance(subset, weight, workdir):
    path = os.path.join(workdir, 'Montserrat-%s-%d.ttf' % (subset, weight))
    if not os.path.exists(path):
        font = TTFont(os.path.join(FONTS, 'Montserrat-%s.woff2' % subset))
        static = instancer.instantiateVariableFont(font, {'wght': weight})
        static.flavor = None
        static.save(path)
    return path


HEAD = '''/* Generated by tools/ui_assets/make_fonts.py: Montserrat %(weight)d, %(size)d px,
 * 4 bpp, Latin + Cyrillic. Montserrat is licensed under the SIL Open Font
 * License 1.1 (see tools/ui_assets/README.md). Do not edit. */
#include "lvgl.h"

LV_FONT_DECLARE(%(fallback)s);
'''

TAIL = '''
static const lv_font_fmt_txt_dsc_t font_dsc = {
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = &%(kern)s,
    .kern_scale = %(kern_scale)s,
    .cmap_num = %(cmap_num)s,
    .bpp = 4,
    .kern_classes = %(kern_classes)s,
    .bitmap_format = 0,
};

const lv_font_t %(name)s = {
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = %(line_height)s,
    .base_line = %(base_line)s,
    .cap_height = %(cap_height)d,
    .x_height = %(x_height)d,
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = %(underline_position)s,
    .underline_thickness = %(underline_thickness)s,
    .static_bitmap = 1,
    .dsc = &font_dsc,
    .fallback = &%(fallback)s,
    .user_data = NULL,
};
'''


def field(text, name):
    match = re.search(r'\.%s = ([^,\s]+),?' % name, text)
    if not match:
        raise SystemExit('field %s not found' % name)
    return match.group(1)


def main():
    conv = sys.argv[1]
    os.makedirs(OUT, exist_ok=True)
    with tempfile.TemporaryDirectory() as workdir:
        for size, weight in STYLES:
            name = 'nav_font_%d_%d' % (size, weight)
            out = os.path.join(OUT, name + '.c')
            latin = instance('latin', weight, workdir)
            subprocess.run(['node', conv, '--size', str(size), '--bpp', '4',
                            '--format', 'lvgl', '--no-compress', '--no-prefilter',
                            '--force-fast-kern-format', '--lv-include', 'lvgl.h',
                            '--font', latin, '--autohint-off', '-r', LATIN,
                            '--font', instance('cyrillic', weight, workdir), '--autohint-off',
                            '-r', CYRILLIC, '-o', out], check=True)
            text = open(out, encoding='utf-8').read()
            # Keep the glyph tables, replace the version-specific wrapper.
            start = text.index('/*Store the image of the glyphs*/')
            end = text.index('/*--------------------\n *  ALL CUSTOM DATA')
            body = text[start:end]
            font = TTFont(latin)
            os2, hhea = font['OS/2'], font['hhea']
            upm = float(font['head'].unitsPerEm)
            # Browser line metrics: ascent and descent rounded separately,
            # so a label placed at a CSS text box top has the same baseline.
            ascent = round(hhea.ascent * size / upm)
            descent = round(-hhea.descent * size / upm)
            values = {
                'name': name, 'size': size, 'weight': weight,
                'fallback': 'lv_font_montserrat_%d' % BUILTIN[size],
                'kern': field(text, 'kern_dsc').lstrip('&'),
                'kern_scale': field(text, 'kern_scale'),
                'cmap_num': field(text, 'cmap_num'),
                'kern_classes': field(text, 'kern_classes'),
                'line_height': ascent + descent,
                'base_line': descent,
                'underline_position': field(text, 'underline_position'),
                'underline_thickness': field(text, 'underline_thickness'),
                'cap_height': round(os2.sCapHeight * size / 1000.0),
                'x_height': round(os2.sxHeight * size / 1000.0),
            }
            open(out, 'w', encoding='utf-8').write(
                HEAD % values + '\n' + body + TAIL % values)
            print(name, values['line_height'], values['base_line'], os.path.getsize(out))


if __name__ == '__main__':
    main()
